let LANG = 'id';
try { const stored = localStorage.getItem('restopilot_lang'); if (stored === 'en' || stored === 'id') LANG = stored; } catch (error) { /* storage unavailable */ }
function t(key) { return I18N[LANG]?.[key] ?? I18N.en[key] ?? key; }
function applyI18nStatic(root = document) {
  root.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-html]').forEach(el => { el.innerHTML = t(el.dataset.i18nHtml); });
  root.querySelectorAll('[data-i18n-attr]').forEach(el => {
    el.dataset.i18nAttr.split(';').forEach(pair => {
      const idx = pair.indexOf(':'); if (idx < 1)return;
      const attr = pair.slice(0, idx).trim(), key = pair.slice(idx + 1).trim();
      if (attr && key) el.setAttribute(attr, t(key));
    });
  });
}
function updateLangToggle() {
  document.querySelectorAll('.lang-toggle [data-lang]').forEach(button => {
    const active = button.dataset.lang === LANG;
    button.classList.toggle('active', active);
    button.setAttribute('aria-pressed', String(active));
  });
}
window.setLang = function(lang) {
  if (lang !== 'id' && lang !== 'en')return;
  LANG = lang;
  try { localStorage.setItem('restopilot_lang', lang); } catch (error) { /* storage unavailable */ }
  document.documentElement.lang = lang;
  document.title = t('doc_title');
  applyI18nStatic();
  updateLangToggle();
  if (typeof window.render === 'function') { try { window.render(); } catch (error) { /* data not loaded yet */ } }
};
document.addEventListener('click', event => {
  const button = event.target.closest('[data-lang]');
  if (button && button.dataset.lang !== LANG) window.setLang(button.dataset.lang);
});
